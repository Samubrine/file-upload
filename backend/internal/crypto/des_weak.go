package crypto

// Masked DES weak and semi-weak keys (least-significant parity bits cleared to 0)
// There are 16 known weak and semi-weak keys for single DES.
var desWeakKeysMasked = [][8]byte{
	// Weak keys
	{0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00}, // 0101010101010101
	{0xfe, 0xfe, 0xfe, 0xfe, 0xfe, 0xfe, 0xfe, 0xfe}, // fefefefefefefefe
	{0x1e, 0x1e, 0x1e, 0x1e, 0x0e, 0x0e, 0x0e, 0x0e}, // 1f1f1f1f0e0e0e0e
	{0xe0, 0xe0, 0xe0, 0xe0, 0xf0, 0xf0, 0xf0, 0xf0}, // e0e0e0e0f1f1f1f1

	// Semi-weak keys
	{0x00, 0xfe, 0x00, 0xfe, 0x00, 0xfe, 0x00, 0xfe}, // 01fe01fe01fe01fe
	{0xfe, 0x00, 0xfe, 0x00, 0xfe, 0x00, 0xfe, 0x00}, // fe01fe01fe01fe01
	{0x1e, 0xe0, 0x1e, 0xe0, 0x0e, 0xf0, 0x0e, 0xf0}, // 1fe01fe00ef10ef1
	{0xe0, 0x1e, 0xe0, 0x1e, 0xf0, 0x0e, 0xf0, 0x0e}, // e01fe01ff10ef10e
	{0x00, 0xe0, 0x00, 0xe0, 0x00, 0xf0, 0x00, 0xf0}, // 01e001e001f101f1
	{0xe0, 0x00, 0xe0, 0x00, 0xf0, 0x00, 0xf0, 0x00}, // e001e001f101f101
	{0x1e, 0xfe, 0x1e, 0xfe, 0x0e, 0xfe, 0x0e, 0xfe}, // 1ffe1ffe0efe0efe
	{0xfe, 0x1e, 0xfe, 0x1e, 0xfe, 0x0e, 0xfe, 0x0e}, // fe1ffe1ffe0efe0e
	{0x00, 0x1e, 0x00, 0x1e, 0x00, 0x0e, 0x00, 0x0e}, // 011f011f010e010e
	{0x1e, 0x00, 0x1e, 0x00, 0x0e, 0x00, 0x0e, 0x00}, // 1f011f010e010e01
	{0xe0, 0xfe, 0xe0, 0xfe, 0xf0, 0xfe, 0xf0, 0xfe}, // e0fee0fef1fef1fe
	{0xfe, 0xe0, 0xfe, 0xe0, 0xfe, 0xf0, 0xfe, 0xf0}, // fee0fee0fef1fef1
}

// IsDESWeakKey reports whether an 8-byte key is one of the 16 weak or semi-weak DES keys,
// regardless of parity bits.
func IsDESWeakKey(key []byte) bool {
	if len(key) != 8 {
		return false
	}
	var masked [8]byte
	for i := 0; i < 8; i++ {
		masked[i] = key[i] & 0xfe
	}
	for _, wk := range desWeakKeysMasked {
		if masked == wk {
			return true
		}
	}
	return false
}

